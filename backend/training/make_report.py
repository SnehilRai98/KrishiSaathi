"""Write docs/model_report.md from models/model_card.json, so published numbers always match the measurements.

    python training/make_report.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARD = ROOT / "models" / "model_card.json"
OUT = ROOT.parent / "docs" / "model_report.md"


def pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def pretty(label: str) -> str:
    crop, _, condition = label.partition("___")
    return f"{crop.replace('_', ' ')}: {condition.replace('_', ' ')}"


def main() -> int:
    card = json.loads(CARD.read_text(encoding="utf-8"))
    m = card["metrics"]
    f, lab, nl = m["field_test"], m["lab_test"], m["non_leaf"]
    lines = [
        "# Crop model report",
        "",
        f"Generated by `backend/training/make_report.py` from `models/model_card.json` (model `{card['model_version']}`, {card['created']}).",
        "Every number below was measured by `backend/training/evaluate_field_model.py` on photos the model never trained on.",
        "",
        "## Summary",
        "",
        "| Test set | Original lab-only model | Field-tuned model |",
        "| --- | --- | --- |",
        f"| {f['n']} real field photos (PlantDoc test split), right class | {pct(f['baseline_top1'])} | **{pct(f['top1'])}** |",
        f"| Same photos, right crop | {pct(f['baseline_crop_top1'])} | **{pct(f['crop_top1'])}** |",
        f"| {lab['n']} clean lab photos (PlantVillage sample) | {pct(lab['baseline_top1'])} | {pct(lab['top1'])} |",
        f"| {nl['n']} non-leaf photos shown as a confident result | {pct(nl['baseline_shown_as_result'])} | {pct(nl['shown_as_result'])} |",
        "",
        f"With {f['n']} photos the margin of error on the field figures is roughly plus or minus 6 percentage points. "
        "On a broader 1,080-photo PlantDoc sample (which included training-split photos) the original model scored 13.3% (crop 29.8%), "
        "so the original model's field accuracy is somewhere between 13% and 27% depending on the photos. Either way it was not usable in a field.",
        "",
        "The lab figure went down slightly after field tuning. The non-leaf set is tiny (a few ordinary photos and graphics), so it proves little.",
        "",
        "## How often it answers, and how often it is right",
        "",
        f"Confidence was calibrated with one temperature ({card['temperature']:.2f}) fitted on a field validation split "
        f"(expected calibration error {f['ece_before_calibration']:.3f} to {f['ece_after_calibration']:.3f}). "
        f"The app withholds an answer below a score of {card['low_confidence_threshold']:.0%}.",
        "",
        "| Score at least | Share of field photos answered | Right when answered |",
        "| --- | --- | --- |",
    ]
    for row in f["selective"]:
        acc = "n/a" if row["accuracy_when_answered"] is None else pct(row["accuracy_when_answered"])
        lines.append(f"| {row['threshold']:.0%} | {pct(row['coverage'])} | {acc} |")
    lines += ["", "## Per class (field test)", "",
              "`Recognised` is how often photos of that class were identified correctly. `Right when it said it` is how often the model's answer was correct when it named that class (shown only when it named it at least 5 times). Classes not listed had no field photos and are lab-only.",
              "", "| Class | Test photos | Recognised | Right when it said it |", "| --- | --- | --- | --- |"]
    per_pred = f.get("per_prediction", {})
    for label, row in sorted(f["per_class"].items(), key=lambda kv: kv[1]["top1"]):
        pred = per_pred.get(label)
        said = pct(pred["precision"]) if pred and pred["n_predicted"] >= 5 else "too few"
        lines.append(f"| {pretty(label)} | {row['n']} | {pct(row['top1'])} | {said} |")
    lab_only = sorted(pretty(k) for k, v in card["class_evidence"].items() if v == "lab_only")
    lines += ["", "## Classes with lab photos only", "", "; ".join(lab_only) + ".", "",
              "## Training data", "", "| Data | Photos |", "| --- | --- |"]
    labels = {
        "plantdoc_train_photos": "PlantDoc train split (field), used to fit",
        "plantdoc_val_photos": "PlantDoc train split, held for early stopping and calibration",
        "plantdoc_test_photos": "PlantDoc test split, used only for final evaluation",
        "plantvillage_train_photos": "PlantVillage lab photos used to fit",
        "background_train_photos": "Non-leaf photos used to fit the background class",
        "background_test_photos": "Non-leaf photos held out for evaluation",
        "synthetic_backgrounds": "Synthetic backgrounds (flat colours, gradients, noise)",
    }
    for key, text in labels.items():
        lines.append(f"| {text} | {card['training'].get(key, 'n/a')} |")
    lines += ["", "## Limitations", ""] + [f"- {item}" for item in card["limitations"]]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
